// Embed the built-in device profiles in the library, so they load without a
// filesystem (@node-net/netconf/core works in any runtime). profiles/*.json stays the
// source; this writes src/devices/builtin-profiles.ts from it.
//
//   node scripts/gen-builtin-profiles.mjs          write the file
//   node scripts/gen-builtin-profiles.mjs --check  fail if it is out of date
//
// The build runs it, and a unit test fails if the committed file is stale.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const PROFILES = fileURLToPath(new URL('../profiles/', import.meta.url));
export const TARGET = fileURLToPath(new URL('../src/devices/builtin-profiles.ts', import.meta.url));

/** The generated module's text. */
export function render() {
  const names = readdirSync(PROFILES)
    .filter((n) => n.endsWith('.json') && !n.endsWith('.schema.json'))
    .sort();
  const entries = names.map((name) => {
    // Re-serialised compactly: what matters is the data, not the file's layout.
    const json = JSON.stringify(JSON.parse(readFileSync(PROFILES + name, 'utf8')));
    return `  { name: ${JSON.stringify(name)}, json: ${JSON.stringify(json)} },`;
  });
  return [
    '// Generated by scripts/gen-builtin-profiles.mjs from profiles/*.json. Do not edit.',
    '',
    '/** @internal The built-in profiles, as the JSON text of each file in profiles/. */',
    'export const BUILTIN_PROFILE_FILES: readonly { readonly name: string; readonly json: string }[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== text) {
      console.error('src/devices/builtin-profiles.ts is out of date: run node scripts/gen-builtin-profiles.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, text);
  }
}
